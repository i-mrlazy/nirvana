// Helper function to localize Story items
export function getLocalizedStories(language: LanguageCode): Story[] {
  if (language === 'en') return STORIES_DATA;
  return STORIES_DATA.map(story => {
    const loc = STORY_TRANSLATIONS[story.id]?.[language];
    if (!loc) return story;
    return {
      ...story,
      title: loc.title || story.title,
      question: loc.question || story.question,
      summary: loc.summary || story.summary,
      category: (loc.category as any) || story.category,
      content: loc.content || story.content,
    };
  });
}

export function getLocalizedStory(storyId: string, language: LanguageCode): Story {
  const stories = getLocalizedStories(language);
  return stories.find(s => s.id === storyId) || stories[0];
}

